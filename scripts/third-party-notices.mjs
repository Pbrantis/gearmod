// Gera THIRD-PARTY-NOTICES.md com as licenças das dependências que vão dentro do app.
//
// Raízes: as `dependencies` de apps/desktop (carregadas em tempo de execução) mais as dependências de interface que o Vite empacota
// no renderer (React, CodeMirror, xterm...), que ficam em `devDependencies` para não entrarem duas vezes no instalador.
// Cada raiz entra com tudo o que ela puxa. Rode na raiz do repositório: `node scripts/third-party-notices.mjs`.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const desktop = join(root, 'apps', 'desktop')
const pnpm = process.platform === 'win32' ? 'pnpm.cmd' : 'pnpm'
const run = (args, cwd) => JSON.parse(execFileSync(pnpm, args, { cwd, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, shell: process.platform === 'win32' }))

const manifest = JSON.parse(readFileSync(join(desktop, 'package.json'), 'utf8'))
const bundledDev = (name) => /^(react|react-dom)$/.test(name) || /^@(codemirror|lezer|xterm)\//.test(name)
const roots = new Set([...Object.keys(manifest.dependencies ?? {}), ...Object.keys(manifest.devDependencies ?? {}).filter(bundledDev)])
roots.delete('@gearmod/contracts')

// Fecho transitivo a partir das raízes, pela árvore que o pnpm resolveu.
const tree = run(['list', '--json', '--depth', 'Infinity'], desktop).find((project) => project.name === '@gearmod/desktop')
const wanted = new Set()
const visit = (name, node) => {
  const id = `${name}@${node.version}`
  if (wanted.has(id)) return
  wanted.add(id)
  for (const [child, value] of Object.entries(node.dependencies ?? {})) visit(child, value)
}
for (const group of [tree.dependencies ?? {}, tree.devDependencies ?? {}]) {
  for (const [name, node] of Object.entries(group)) if (roots.has(name)) visit(name, node)
}

const licenses = run(['licenses', 'list', '--json'], root)
const entries = []
for (const group of Object.values(licenses)) {
  for (const pkg of group) for (const version of pkg.versions) if (wanted.has(`${pkg.name}@${version}`)) entries.push({ name: pkg.name, version, license: pkg.license, path: pkg.paths?.[pkg.versions.indexOf(version)] ?? pkg.paths?.[0] })
}
entries.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))

const licenseFile = (dir) => {
  if (!dir || !existsSync(dir)) return ''
  const file = readdirSync(dir).find((name) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(name))
  return file ? readFileSync(join(dir, file), 'utf8').trim() : ''
}
const texts = new Map()
let body = ''
for (const entry of entries) {
  const text = licenseFile(entry.path)
  const key = text ? createHash('sha256').update(text).digest('hex').slice(0, 12) : ''
  if (text && !texts.has(key)) texts.set(key, text)
  body += `- **${entry.name}** ${entry.version} — ${entry.license}${key ? ` (text ${key})` : ' (no license file in the package; see its repository)'}\n`
}

let out = '# Third-party notices\n\nGearMod includes the open source packages below. Each one is distributed under its own license; GearMod itself is under the PolyForm Shield License 1.0.0 (see `LICENSE`).\n\n'
out += `Generated by \`scripts/third-party-notices.mjs\` — ${entries.length} packages.\n\n## Packages\n\n${body}\n## License texts\n\n`
for (const [key, text] of texts) out += `### Text ${key}\n\n\`\`\`text\n${text}\n\`\`\`\n\n`
writeFileSync(join(root, 'THIRD-PARTY-NOTICES.md'), out)
console.log(`THIRD-PARTY-NOTICES.md: ${entries.length} pacotes, ${texts.size} textos de licença`)
